func TestParseGoProfile(t *testing.T) {
	profile := "mode: set\n" +
		"example.com/svc/lib/lib.go:3.24,4.11 1 1\n" +
		"example.com/svc/lib/lib.go:4.11,6.3 1 0\n" +
		// Names as //line directives give them: cover keeps the base name
		// in the package directory, spaces and colons included.
		"example.com/svc/lib/my file.go:10.0,10.0 1 1\n" +
		"example.com/svc/lib/yaccpar:1.0,2.0 1 0\n" +
		// A directive without a file name gives the directory itself.
		"example.com/svc/lib/.:30.0,30.0 1 1\n" +
		// No repository file has this name; it is left out.
		`example.com/svc/lib/C:\x\real.go:20.0,20.0 1 1` + "\n"
	coverage, err := parseGoProfile([]byte(profile), "example.com/svc", "svc")
	if err != nil {
		t.Fatalf("parseGoProfile: %v", err)
	}
	lib := coverage["svc/lib/lib.go"]
	if lib[3] != 1 || lib[4] != 1 || lib[5] != 0 || lib[6] != 0 {
		t.Fatalf("coverage of lib.go = %v (line 4 is shared and ran)", lib)
	}
	want := []string{"svc/lib", "svc/lib/lib.go", "svc/lib/my file.go", "svc/lib/yaccpar"}
	if got := slices.Sorted(maps.Keys(coverage)); !slices.Equal(got, want) {
		t.Fatalf("files = %q, want %q", got, want)
	}
	for _, bad := range []string{
		"garbage",
		"mode: set\nexample.com/svc/lib/lib.go:3.24,4.11 1\n",
		"mode: set\nexample.com/svc/lib/lib.go:x.24,4.11 1 1\n",
		// -coverpkg=./... covers the module's own packages only.
		"mode: set\nother.com/x/y.go:1.1,2.2 1 1\n",
		"mode: set\nexample.com/svc/../../etc/passwd:1.1,2.2 1 1\n",
		"mode: set\nexample.com/svc/..:1.1,2.2 1 1\n",
	} {
		if _, err := parseGoProfile([]byte(bad), "example.com/svc", "svc"); err == nil {
			t.Errorf("profile %q must be an error", bad)
		}
	}
}

const libTest = "package lib\n\nimport \"testing\"\n\nfunc TestCovered(t *testing.T) { if Covered(1) != 1 { t.Fatal() } }\n"

// goyacc writes "//line yaccpar:1" above the parser driver it copies in, a
// file that is never on disk, and an excluded or untested file may hold
// any directive. The module's suite still runs and reports coverage as
// cover wrote it: the tests gate checks the files it judges (R2-CR-1).
func TestGoTestReportsCoverageAsWritten(t *testing.T) {
	root := repoWith(t, map[string]string{
		"svc/go.mod":          "module example.com/svc\n\ngo 1.25\n",
		"svc/lib/lib.go":      strings.Replace(goLib, "func Uncovered", "//line lib.go:5000\nfunc Uncovered", 1),
		"svc/lib/lib_test.go": libTest,
		"svc/internal/infrastructure/parser/y.go":      "// Code generated by goyacc. DO NOT EDIT.\n\npackage parser\n\n//line yaccpar:1\nfunc Parse(x int) int {\n\tif x > 0 {\n\t\treturn 1\n\t}\n\treturn 2\n}\n",
		"svc/internal/infrastructure/parser/y_test.go": "package parser\n\nimport \"testing\"\n\nfunc TestParse(t *testing.T) { Parse(1) }\n",
	})
	result, err := New(root, nil).GoTest(t.Context(), "svc")
	if err != nil || result.Failed {
		t.Fatalf("GoTest = %+v, %v; line directives must not make the module's suite unusable", result, err)
	}
	if lib := result.Coverage["svc/lib/lib.go"]; lib[4] != 1 || lib[5001] != 0 {
		t.Fatalf("coverage of lib.go = %v, want line 4 run and the moved line 5001 as cover wrote it", lib)
	}
	if result.Coverage["svc/internal/infrastructure/parser/yaccpar"] == nil {
		t.Fatalf("coverage = %v, want the yaccpar entry as cover wrote it", result.Coverage)
	}
}

// Cover credits the code after "//line real.go:10" in a file beside
// real.go to real.go, so code that ran there would pass for real.go's
// untested lines (R2-SEC-1): what the tests gate asks the Go sources about
// (goanalyzer's GoForeignCoverage), whatever ran the suite. A name go build
// ignores, a symlink to a directory here, is no source and leaves the
// suite usable (R3-SEC-5).
func TestGoTestCreditsCodeAfterADirectiveToTheFileItNames(t *testing.T) {
	const real = "package p\n\nfunc Real(x int) int {\n\tif x > 0 {\n\t\treturn 1\n\t}\n\treturn 2\n}\n\nfunc Untested() int {\n\ta := 1\n\ta++\n\treturn a\n}\n"
	root := repoWith(t, map[string]string{
		"go.mod":           "module example.com/m\n\ngo 1.25\n",
		"p/real.go":        real,
		"p/real_string.go": "// Code generated by stringer. DO NOT EDIT.\n\npackage p\n\n//line real.go:10\nfunc Lend() int {\n\tb := 1\n\treturn b\n}\n",
		"p/real_test.go":   "package p\n\nimport \"testing\"\n\nfunc TestReal(t *testing.T) { Real(1); Lend() }\n",
	})
	if err := os.Symlink("..", filepath.Join(root, "p", "_link.go")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	result, err := New(root, nil).GoTest(t.Context(), "")
	if err != nil || result.Failed {
		t.Fatalf("GoTest = %+v, %v", result, err)
	}
	if lines := result.Coverage["p/real.go"]; lines[10] != 1 || lines[11] != 1 {
		t.Fatalf("coverage of real.go = %v; cover is expected to credit Lend to Untested's lines", lines)
	}
}
