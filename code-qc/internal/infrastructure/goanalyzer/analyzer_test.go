package goanalyzer

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"millennium-code-qc/internal/domain"
)

func repoWith(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, content := range files {
		full := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func analyze(t *testing.T, root, path, src string) domain.FileFacts {
	t.Helper()
	facts, err := New(root).Analyze(t.Context(), path, []byte(src))
	if err != nil {
		t.Fatalf("Analyze: %v", err)
	}
	return facts
}

func TestImportsAreClassifiedAgainstTheModule(t *testing.T) {
	root := repoWith(t, map[string]string{
		"services/game/api/go.mod": "// comment\nmodule game // the service\n\ngo 1.25\n",
	})
	src := `package domain

import (
	"fmt"
	"game/internal/application/port"
	"github.com/redis/go-redis/v9"
	"game"
)
`
	facts := analyze(t, root, "services/game/api/internal/domain/user.go", src)
	want := []domain.Import{
		{Path: "fmt", Line: 4, Kind: domain.ImportStandard},
		{Path: "game/internal/application/port", Line: 5, Kind: domain.ImportProject, Target: "services/game/api/internal/application/port"},
		{Path: "github.com/redis/go-redis/v9", Line: 6, Kind: domain.ImportExternal},
		{Path: "game", Line: 7, Kind: domain.ImportProject, Target: "services/game/api"},
	}
	if !slices.Equal(facts.Imports, want) {
		t.Fatalf("imports = %+v\nwant      %+v", facts.Imports, want)
	}
}

func TestModuleAtRepositoryRoot(t *testing.T) {
	root := repoWith(t, map[string]string{"go.mod": "module \"example.com/app\"\n"})
	facts := analyze(t, root, "internal/a/a.go", "package a\nimport _ \"example.com/app/internal/b\"\n")
	if got := facts.Imports[0]; got.Kind != domain.ImportProject || got.Target != "internal/b" {
		t.Fatalf("import = %+v, want project import of internal/b", got)
	}
}

func TestFunctionsAreMeasuredAndKeyed(t *testing.T) {
	root := repoWith(t, map[string]string{"go.mod": "module m\n"})
	src := `package a

type Set[T comparable] struct{}

func (s *Set[T]) Add(v T) {
	if true {
	}
}

func (r Repo) Get() {}

func init() {}

func init() {}

func helper() {
}
`
	facts := analyze(t, root, "a.go", src)
	var keys []string
	for _, fn := range facts.Functions {
		keys = append(keys, fn.Key)
	}
	if !slices.Equal(keys, []string{"Set.Add", "Repo.Get", "init", "init#2", "helper"}) {
		t.Fatalf("keys = %q", keys)
	}
	add := facts.Functions[0]
	if add.Line != 5 || add.Lines != 4 || add.Cognitive != 1 || add.Nesting != 1 {
		t.Fatalf("Set.Add measured as %+v", add)
	}
	if helper := facts.Functions[4]; helper.Lines != 2 {
		t.Fatalf("helper is 2 lines, got %+v", helper)
	}
}

func TestFileFlags(t *testing.T) {
	root := repoWith(t, map[string]string{"go.mod": "module m\n"})
	generated := analyze(t, root, "gen.go", "// Code generated by protoc. DO NOT EDIT.\n\npackage a\n")
	if !generated.Generated || generated.Test {
		t.Fatalf("generated file flags: %+v", generated)
	}
	test := analyze(t, root, "a_test.go", "package a\n")
	if !test.Test || test.Generated {
		t.Fatalf("test file flags: %+v", test)
	}
}

func TestAnalyzeFailsClosed(t *testing.T) {
	root := repoWith(t, map[string]string{"go.mod": "module m\n", "nomod/go.mod": "go 1.25\n"})
	tests := []struct {
		name, root, path, src, want string
	}{
		{"syntax error", root, "a.go", "package a\nfunc {", "parse a.go"},
		{"no go.mod", t.TempDir(), "a.go", "package a\n", "no go.mod"},
		{"go.mod without module", root, "nomod/a.go", "package a\n", "no module directive"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := New(tt.root).Analyze(t.Context(), tt.path, []byte(tt.src))
			if err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("err = %v, want it to mention %q", err, tt.want)
			}
		})
	}
}

func TestCommentsAndConstructs(t *testing.T) {
	root := repoWith(t, map[string]string{"go.mod": "module m\n"})
	src := `package a

import (
	"crypto/tls"
	"os/exec"
)

// Run does things. TODO(#12): more
func Run(ctx context.Context, cmd string) {
	_ = &tls.Config{InsecureSkipVerify: true} //nolint:gosec // test server only
	_ = exec.Command("sh", "-c", cmd)
	_ = exec.CommandContext(ctx, "bash", "-c", cmd)
	_ = exec.Command("ls", "-c")
	_ = exec.Command("git", "status")
}
`
	facts := analyze(t, root, "a.go", src)
	if len(facts.Comments) != 2 || facts.Comments[0].Line != 8 || !strings.Contains(facts.Comments[1].Text, "nolint") {
		t.Fatalf("comments = %+v", facts.Comments)
	}
	want := []domain.Construct{
		{Kind: domain.ConstructTLSVerifyOff, Line: 10, Detail: "InsecureSkipVerify: true"},
		{Kind: domain.ConstructShellCommand, Line: 11, Detail: `exec.Command("sh", "-c", ...)`},
		{Kind: domain.ConstructShellCommand, Line: 12, Detail: `exec.CommandContext("bash", "-c", ...)`},
	}
	if !slices.Equal(facts.Constructs, want) {
		t.Fatalf("constructs = %+v\nwant         %+v", facts.Constructs, want)
	}
}
