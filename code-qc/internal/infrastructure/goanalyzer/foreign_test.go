// treeWith writes files under a new directory and returns it.
func treeWith(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, content := range files {
		full := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func symlink(t *testing.T, target, link string) {
	t.Helper()
	if err := os.Symlink(target, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
}

// Cover credits the code after "//line real.go:5" in a file beside real.go
// to real.go, so code that ran there would pass for real.go's untested
// lines (R2-SEC-1). Every Go source of the directory counts, test files and
// files no build includes too, and only that directory is read (R3-PERF-1).
// What go build never reads lends nothing (R3-SEC-5).
func TestGoForeignCoverage(t *testing.T) {
	root := treeWith(t, map[string]string{
		"p/real.go":         "package p\n\n//line real.go:1\nfunc Real() {}\n",
		"p/real_string.go":  "// Code generated by stringer. DO NOT EDIT.\n\npackage p\n\n//line real.go:10\nfunc Lend() int { return 1 }\n",
		"p/elsewhere.go":    "package p\n\n//line ../q/other.go:3\nfunc O() int { return 5 }\n",
		"p/ignored_test.go": "package p\n\n/*line real.go:1*/\n",
		"p/windows.go":      "//go:build windows\n\npackage p\n\n//line real.go:20\nfunc W() {}\n",
		"p/nofile.go":       "package p\n\n//line :5\nfunc N() {}\n",
		"p/notes.txt":       "//line real.go:1\n",
		"p/_skip.go":        "package p\n\n//line real.go:30\n",
		"p/.hidden.go":      "package p\n\n//line real.go:40\n",
		"p/sub.go/keep.txt": "a directory named like a Go file\n",
		"q/q.go":            "package q\n\n//line real.go:1\nfunc Q() int { return 1 }\n",
	})
	symlink(t, "..", filepath.Join(root, "p", "_link.go"))
	symlink(t, "sub.go", filepath.Join(root, "p", "dirlink.go"))
	foreign, err := NewSources(root).GoForeignCoverage("p")
	if err != nil {
		t.Fatalf("GoForeignCoverage: %v", err)
	}
	got := map[string]string{}
	for _, f := range foreign {
		got[f.File+":"+f.Directive.Text] = f.Credited
	}
	want := map[string]string{
		"p/real_string.go://line real.go:10":    "p/real.go",
		"p/elsewhere.go://line ../q/other.go:3": "p/other.go",
		"p/ignored_test.go:/*line real.go:1*/":  "p/real.go",
		"p/windows.go://line real.go:20":        "p/real.go",
	}
	if len(got) != len(want) {
		t.Fatalf("foreign = %v, want %v", got, want)
	}
	for k, credited := range want {
		if got[k] != credited {
			t.Fatalf("foreign = %v, want %v", got, want)
		}
	}
}

// Code in the repository root's own directory is credited within it.
func TestGoForeignCoverageAtTheRoot(t *testing.T) {
	root := treeWith(t, map[string]string{"gen.go": "package m\n\n//line main.go:3\nfunc G() {}\n"})
	foreign, err := NewSources(root).GoForeignCoverage(".")
	want := domain.ForeignCoverage{File: "gen.go", Directive: domain.LineDirective{Line: 3, Text: "//line main.go:3", File: "main.go"}, Credited: "main.go"}
	if err != nil || len(foreign) != 1 || foreign[0] != want {
		t.Fatalf("GoForeignCoverage(.) = %+v, %v, want %+v", foreign, err, want)
	}
}

// A source that cannot be read could lend anything, so what the directory
// lends is unknown: an error, which the tests gate turns into a finding on
// the files it judges there.
func TestGoForeignCoverageFailsOnWhatItCannotRead(t *testing.T) {
	root := treeWith(t, map[string]string{"p/a.go": "package p\n"})
	symlink(t, "gone.go", filepath.Join(root, "p", "dangling.go"))
	if _, err := NewSources(root).GoForeignCoverage("p"); err == nil || !strings.Contains(err.Error(), "dangling.go") {
		t.Fatalf("GoForeignCoverage = %v, want an error naming dangling.go", err)
	}
	for _, dir := range []string{"missing", "../p", "/p", ""} {
		if _, err := NewSources(root).GoForeignCoverage(dir); err == nil {
			t.Errorf("GoForeignCoverage(%q) must be an error", dir)
		}
	}
}

// A file over the limit is not read whole: whether it lends coverage
// cannot be checked.
func TestGoForeignCoverageOverTheLimit(t *testing.T) {
	root := treeWith(t, map[string]string{"p/big.go": "package p\n\n//line real.go:1\n"})
	sources := &Sources{root: root, limit: 10}
	if _, err := sources.GoForeignCoverage("p"); err == nil || !strings.Contains(err.Error(), "larger than 10 bytes") {
		t.Fatalf("GoForeignCoverage = %v, want the size limit", err)
	}
	if sources := NewSources(root); sources.limit != maxGoSourceBytes {
		t.Fatalf("limit = %d, want %d", sources.limit, maxGoSourceBytes)
	}
}
