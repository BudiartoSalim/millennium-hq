func TestTypeScriptImports(t *testing.T) {
	a, _ := typeScriptProject(t, webProject)
	src := `import { readFile } from 'node:fs';
import path from 'path';
import type { X } from './stream';
import { y } from '@/lib/format';
import React from 'react';
export { x } from './stream';
const legacy = require('../../lib/format');
const lazy = await import('./missing');
`
	facts := run(t, a, "web/src/features/chat/view.ts", src)
	want := []domain.Import{
		{Path: "node:fs", Line: 1, Kind: domain.ImportStandard},
		{Path: "path", Line: 2, Kind: domain.ImportStandard},
		{Path: "./stream", Line: 3, Kind: domain.ImportProject, Target: "web/src/features/chat/stream.ts"},
		{Path: "@/lib/format", Line: 4, Kind: domain.ImportProject, Target: "web/src/lib/format.ts"},
		{Path: "react", Line: 5, Kind: domain.ImportExternal},
		{Path: "./stream", Line: 6, Kind: domain.ImportProject, Target: "web/src/features/chat/stream.ts"},
		{Path: "../../lib/format", Line: 7, Kind: domain.ImportProject, Target: "web/src/lib/format.ts"},
		{Path: "./missing", Line: 8, Kind: domain.ImportProject, Target: "web/src/features/chat/missing"},
	}
	if !slices.Equal(facts.Imports, want) {
		t.Fatalf("imports = %+v\nwant      %+v", facts.Imports, want)
	}
}

func TestTypeScriptMetrics(t *testing.T) {
	a, _ := typeScriptProject(t, webProject)
	tests := []struct {
		name, src          string
		cognitive, nesting int
	}{
		{"empty", "function f() {}", 0, 0},
		{"if, else if, else: +1 +1 +1", "function f(a: boolean, b: boolean) { if (a) {} else if (b) {} else {} }", 3, 1},
		{"for, if, while: +1 +2 +3", "function f(xs: number[]) { for (const x of xs) { if (x) { while (true) { break; } } } }", 6, 3},
		{"ternary: +1", "function f(a: boolean) { return a ? 1 : 2; }", 1, 1},
		{"&& then ||: +2, plus if", "function f(a: boolean, b: boolean, c: boolean) { if (a && b || c) {} }", 3, 1},
		{"?? run: +1", "function f(a?: number, b?: number) { return a ?? b ?? 0; }", 1, 0},
		{"switch +1, if in case +2", "function f(x: number, y: boolean) { switch (x) { case 1: if (y) {} } }", 3, 2},
		{"catch: +1", "function f() { try { g(); } catch (e) { h(); } }", 1, 1},
		{"nested arrow nests: if +2", "function f(a: boolean) { return () => { if (a) {} }; }", 2, 2},
		{"labelled continue: +1 +2 +1", "function f() { outer: for (;;) { for (;;) { continue outer; } } }", 4, 2},
		{"recursion: if +1, call +1", "function fact(n: number): number { if (n <= 1) { return 1; } return n * fact(n - 1); }", 2, 1},
		{"function types in annotations do not nest", "function f(cb: (x: number) => void) { cb(1); }", 0, 0},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			fn := run(t, a, "web/src/m.ts", tt.src).Functions[0]
			if fn.Cognitive != tt.cognitive || fn.Nesting != tt.nesting {
				t.Fatalf("cognitive %d nesting %d, want %d and %d", fn.Cognitive, fn.Nesting, tt.cognitive, tt.nesting)
			}
		})
	}
}

func TestTypeScriptFunctionKeys(t *testing.T) {
	a, _ := typeScriptProject(t, webProject)
	src := `export function handler() {}
export const App = () => { return null; };
export class Store {
  constructor() {}
  get size() { return 0; }
  add(x: number) { if (x) { this.add(x - 1); } }
  onEvent = () => {};
}
export const api = { list() { return []; }, get: (id: string) => id };
app.get('/users', (req, res) => { res.json([]); });
test('rejects bad input', () => {});
export default function () {}
`
	facts := run(t, a, "web/src/app.ts", src)
	var keys []string
	for _, fn := range facts.Functions {
		keys = append(keys, fn.Key)
	}
	want := []string{"handler", "App", "Store.constructor", "Store.get size", "Store.add", "Store.onEvent",
		"api.list", "api.get", `app.get("/users")`, `test("rejects bad input")`, "default"}
	if !slices.Equal(keys, want) {
		t.Fatalf("keys = %q\nwant  %q", keys, want)
	}
	if add := functionByKey(t, facts, "Store.add"); add.Cognitive != 2 {
		t.Fatalf("Store.add = %+v; if +1, recursion through this +1", add)
	}
}

func TestTypeScriptFlagsCommentsAndConstructs(t *testing.T) {
	a, _ := typeScriptProject(t, webProject)
	src := `// @generated by codegen
import { exec } from 'node:child_process';
// TODO: remove
export function f(el: HTMLElement, input: any) {
  el.innerHTML = input; // eslint-disable-line no-unsanitized/property
  eval('1');
  new Function('return 1');
  exec('ls ' + input);
  const agent = { rejectUnauthorized: false };
  return <div dangerouslySetInnerHTML={{ __html: input }} /> as any;
}
`
	facts := run(t, a, "web/src/__tests__/f.tsx", src)
	if !facts.Generated || !facts.Test {
		t.Fatalf("flags: generated %v test %v", facts.Generated, facts.Test)
	}
	if len(facts.Comments) != 3 || facts.Comments[1].Text != "// TODO: remove" || facts.Comments[2].Line != 5 {
		t.Fatalf("comments = %+v", facts.Comments)
	}
	want := []string{"explicit-any:any", "html-injection:innerHTML", "dynamic-code:eval", "dynamic-code:new Function",
		"shell-command:exec", "tls-verify-off:rejectUnauthorized: false", "html-injection:dangerouslySetInnerHTML", "explicit-any:any"}
	if got := constructKinds(facts); !slices.Equal(got, want) {
		t.Fatalf("constructs = %q\nwant         %q", got, want)
	}
}

func TestTypeScriptFailsClosed(t *testing.T) {
	node, _ := typeScriptFixture(t)
	tests := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"no typescript package", map[string]string{"web/package.json": "{}"}, "the typescript package cannot be loaded"},
		{"typescript 7 without the classic API", map[string]string{
			"web/package.json":                         "{}",
			"web/node_modules/typescript/package.json": `{"name":"typescript","version":"7.0.2","main":"index.js"}`,
			"web/node_modules/typescript/index.js":     "module.exports = { version: '7.0.2' };",
		}, "TypeScript 7 replaced it"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			a := TypeScript(repoWith(t, tt.files), node)
			t.Cleanup(a.Close)
			if _, err := a.Analyze(t.Context(), "web/a.ts", []byte("export {}\n")); err == nil || !strings.Contains(err.Error(), tt.want) {
				t.Fatalf("err = %v, want it to mention %q", err, tt.want)
			}
		})
	}
	a, _ := typeScriptProject(t, webProject)
	if _, err := a.Analyze(t.Context(), "web/bad.ts", []byte("function {")); err == nil || !strings.Contains(err.Error(), "parse web/bad.ts:1") {
		t.Fatalf("err = %v, want a parse error", err)
	}
}
