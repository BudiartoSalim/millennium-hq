func pythonAnalyzer(t *testing.T, files map[string]string) *Analyzer {
	t.Helper()
	a := Python(repoWith(t, files), pythonCommand(t))
	t.Cleanup(a.Close)
	return a
}

func TestPythonImports(t *testing.T) {
	a := pythonAnalyzer(t, map[string]string{
		"svc/app/tts/__init__.py":    "",
		"svc/app/tts/domain.py":      "",
		"svc/app/tts/engine.py":      "",
		"lib/src/shared/__init__.py": "",
	})
	src := `import json
import os.path
from tts import domain
from tts.engine import Engine
from . import domain as d
from ..app import x
import numpy as np
from __future__ import annotations
`
	facts := run(t, a, "svc/app/tts/service.py", src)
	want := []domain.Import{
		{Path: "json", Line: 1, Kind: domain.ImportStandard},
		{Path: "os.path", Line: 2, Kind: domain.ImportStandard},
		{Path: "tts", Line: 3, Kind: domain.ImportProject, Target: "svc/app/tts"},
		{Path: "tts.engine", Line: 4, Kind: domain.ImportProject, Target: "svc/app/tts/engine"},
		{Path: ".", Line: 5, Kind: domain.ImportProject, Target: "svc/app/tts"},
		{Path: "..app", Line: 6, Kind: domain.ImportProject, Target: "svc/app/app"},
		{Path: "numpy", Line: 7, Kind: domain.ImportExternal},
		{Path: "__future__", Line: 8, Kind: domain.ImportStandard},
	}
	if !slices.Equal(facts.Imports, want) {
		t.Fatalf("imports = %+v\nwant      %+v", facts.Imports, want)
	}
	src = "from shared import util\n"
	if got := run(t, a, "lib/tool.py", src).Imports[0]; got.Kind != domain.ImportProject || got.Target != "lib/src/shared" {
		t.Fatalf("src layout import = %+v", got)
	}
}

func TestPythonMetrics(t *testing.T) {
	a := pythonAnalyzer(t, nil)
	tests := []struct {
		name, src          string
		cognitive, nesting int
	}{
		{"empty", "def f():\n    pass\n", 0, 0},
		{"if elif else: +1 +1 +1", "def f(a, b):\n    if a:\n        pass\n    elif b:\n        pass\n    else:\n        pass\n", 3, 1},
		{"else then nested if is not elif: +1 +1 +2", "def f(a, b):\n    if a:\n        pass\n    else:\n        if b:\n            pass\n", 4, 2},
		{"for, if, while: +1 +2 +3", "def f(xs):\n    for x in xs:\n        if x:\n            while True:\n                break\n", 6, 3},
		{"for-else: +1 +1", "def f(xs):\n    for x in xs:\n        pass\n    else:\n        pass\n", 2, 1},
		{"try with two excepts: +1 +1", "def f():\n    try:\n        pass\n    except ValueError:\n        pass\n    except KeyError:\n        pass\n", 2, 1},
		{"bool runs: and then or: +2, plus if", "def f(a, b, c):\n    if a and b or c:\n        pass\n", 3, 1},
		{"one bool run: +1", "def f(a, b, c):\n    return a and b and c\n", 1, 0},
		{"ternary: +1", "def f(a):\n    return 1 if a else 2\n", 1, 1},
		{"recursion: if +1, call +1", "def fact(n):\n    if n <= 1:\n        return 1\n    return n * fact(n - 1)\n", 2, 1},
		{"nested def nests: if +2", "def f(a):\n    def g():\n        if a:\n            pass\n    return g\n", 2, 2},
		{"match: +1, if in case +2", "def f(x, y):\n    match x:\n        case 1:\n            if y:\n                pass\n", 3, 2},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			fn := run(t, a, "m.py", tt.src).Functions[0]
			if fn.Cognitive != tt.cognitive || fn.Nesting != tt.nesting {
				t.Fatalf("cognitive %d nesting %d, want %d and %d", fn.Cognitive, fn.Nesting, tt.cognitive, tt.nesting)
			}
		})
	}
}

func TestPythonFunctionsCommentsAndConstructs(t *testing.T) {
	a := pythonAnalyzer(t, nil)
	src := `# Code generated by tool. DO NOT EDIT.
import pickle, subprocess, yaml, requests


class Engine:
    def run(self, cmd):  # TODO: tidy
        subprocess.run(cmd, shell=True)
        return self.run(cmd)

    class Inner:
        def go(self):
            pass


def load(data):
    pickle.loads(data)
    yaml.load(data)
    yaml.load(data, Loader=yaml.SafeLoader)
    requests.get("https://x", verify=False)
    eval("1")
`
	facts := run(t, a, "pkg/tests/gen.py", src)
	if !facts.Generated || !facts.Test {
		t.Fatalf("flags: generated %v test %v", facts.Generated, facts.Test)
	}
	if run := functionByKey(t, facts, "Engine.run"); run.Cognitive != 1 || run.Line != 6 || run.Lines != 3 {
		t.Fatalf("Engine.run = %+v (method recursion through self costs 1)", run)
	}
	functionByKey(t, facts, "Engine.Inner.go")
	functionByKey(t, facts, "load")
	if len(facts.Comments) != 2 || facts.Comments[1].Line != 6 || facts.Comments[1].Text != "# TODO: tidy" {
		t.Fatalf("comments = %+v", facts.Comments)
	}
	want := []string{
		"shell-command:shell=True",
		"unsafe-deserialization:pickle.loads",
		"unsafe-deserialization:yaml.load without a safe Loader",
		"tls-verify-off:verify=False",
		"dynamic-code:eval",
	}
	if got := constructKinds(facts); !slices.Equal(got, want) {
		t.Fatalf("constructs = %q\nwant         %q", got, want)
	}
}

func TestPythonErrors(t *testing.T) {
	a := pythonAnalyzer(t, nil)
	if _, err := a.Analyze(t.Context(), "bad.py", []byte("def f(:\n")); err == nil || !strings.Contains(err.Error(), "parse bad.py:1") {
		t.Fatalf("err = %v, want a parse error", err)
	}
	// The process survives a file it cannot parse.
	run(t, a, "ok.py", "x = 1\n")
}

func TestPythonIgnoresPlantedModules(t *testing.T) {
	// A json.py reachable through PYTHONPATH must not replace the standard
	// library module the helper imports. Both the environment filter and -I
	// stop it; the test fails only if both are removed.
	planted := repoWith(t, map[string]string{"json.py": "raise SystemExit('planted module ran')\n"})
	t.Setenv("PYTHONPATH", planted)
	a := Python(repoWith(t, nil), pythonCommand(t))
	t.Cleanup(a.Close)
	run(t, a, "x.py", "import json\n")
}
