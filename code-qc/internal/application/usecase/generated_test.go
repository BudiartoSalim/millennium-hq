// generatedFile is an application-layer Go file with untested logic and an
// over-long function, behind a generated-code marker the change added.
const generatedFile = "svc/internal/application/gen.go"

// markerAnalyzer gives the marked file's facts: one 80-line function behind
// a generated-code marker. The base version is unmarked and short.
type markerAnalyzer struct{}

func (markerAnalyzer) Analyze(_ context.Context, p string, content []byte) (domain.FileFacts, error) {
	switch string(content) {
	case "// Code generated by x. DO NOT EDIT.":
		return domain.FileFacts{Path: p, Generated: true, Functions: []domain.FunctionFacts{{Key: "Run", Line: 3, Lines: 80}}}, nil
	case "package svc":
		return domain.FileFacts{Path: p, Functions: []domain.FunctionFacts{{Key: "Run", Line: 3, Lines: 10}}}, nil
	}
	return domain.FileFacts{}, errors.New("parse " + p + ": syntax error")
}

// markerSource holds the marked file now and its unmarked base.
type markerSource struct{}

func (markerSource) ReadWorking(p string) ([]byte, error) {
	if p != generatedFile {
		return nil, errors.New(p + " is not a regular file")
	}
	return []byte("// Code generated by x. DO NOT EDIT."), nil
}

func (markerSource) ReadAt(_ context.Context, _, p string) ([]byte, bool, error) {
	return []byte("package svc"), p == generatedFile, nil
}

func (markerSource) ChangedLines(context.Context, string, string) (domain.LineSet, error) {
	return domain.LineSet{Ranges: []domain.LineRange{{First: 1, Last: 90}}}, nil
}

// markerRunner runs the module's tests, which never execute line 4.
type markerRunner struct{}

func (markerRunner) GoTest(context.Context, string) (port.TestResult, error) {
	return port.TestResult{Coverage: domain.Coverage{generatedFile: {4: 0}}}, nil
}

func (markerRunner) PythonTest(context.Context, string) (port.TestResult, error) {
	return port.TestResult{}, errors.New("no Python here")
}

func (markerRunner) Command(context.Context, string, domain.TestRecipe) (port.TestResult, error) {
	return port.TestResult{}, errors.New("no recipe here")
}

// markerFinder knows one module, at svc.
type markerFinder struct{}

func (markerFinder) NearestUp(_, marker, _ string) (string, bool) { return "svc", marker == "go.mod" }

// TestGeneratedCodeInTestedLayersIsDeclaredWithExclude: whether a
// tested-layer file is exempt depends on the config's exclude, never on a
// marker in the file (SR-17, AC-11, AC-12).
func TestGeneratedCodeInTestedLayersIsDeclaredWithExclude(t *testing.T) {
	tests := []struct {
		name    string
		exclude []string
		want    string
	}{
		{"marker alone", nil, "tests-missing uncovered-change function-length"},
		{"under exclude", []string{"svc/internal/application/gen.go"}, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := pointsToExclude(t, runMarkerChange(t, tt.exclude).Findings())
			if strings.Join(got, " ") != tt.want {
				t.Fatalf("rules = %q, want %q", got, tt.want)
			}
		})
	}
}

// pointsToExclude lists the rules of findings, and checks that each is on
// the marked file and points to exclude.
func pointsToExclude(t *testing.T, findings []domain.Finding) []string {
	t.Helper()
	var rules []string
	for _, f := range findings {
		rules = append(rules, f.Rule)
		if f.File != generatedFile || !strings.Contains(f.Message, `declare generated files there with "exclude" in the config`) {
			t.Errorf("finding %+v does not point to exclude", f)
		}
	}
	return rules
}

func runMarkerChange(t *testing.T, exclude []string) domain.Report {
	t.Helper()
	pack, err := domain.NewPack(domain.PackInput{
		Name: "clean-architecture", Languages: []string{"go"},
		Layers: []domain.PackLayer{{Name: "domain", Tested: true}, {Name: "application", MayImport: []string{"domain"}, Tested: true}},
		Paths:  map[string]map[string][]string{"go": {"domain": {"internal/domain"}, "application": {"internal/application"}}},
		Guide:  "Business rules live in domain.",
	})
	if err != nil {
		t.Fatalf("NewPack: %v", err)
	}
	cfg, err := domain.NewConfig(domain.ConfigInput{Version: ptr(1), Exclude: exclude, Components: []domain.ComponentInput{
		{Paths: []string{"svc"}, Languages: []string{"go"}, Conventions: []string{"clean-architecture"}},
	}})
	if err != nil {
		t.Fatalf("NewConfig: %v", err)
	}
	cfg.Packs = domain.Catalog{"clean-architecture": pack}
	analyzers := map[domain.Language]port.Analyzer{domain.LanguageGo: markerAnalyzer{}}
	gates := []port.Gate{
		gate.NewTests(analyzers, markerSource{}, markerRunner{}, markerFinder{}),
		gate.NewStructure(analyzers, markerSource{}),
	}
	repo := &fakeRepo{changes: []domain.ChangedFile{{Path: generatedFile, Kind: domain.ChangeModified}}}
	report, err := NewRunGates(NewLoadConfig(fakeSource{cfg: cfg}, repo), repo, gates).Execute(t.Context(), RunGatesInput{Tier: domain.TierFull})
	if err != nil {
		t.Fatalf("Execute: %v", err)
	}
	return report
}
