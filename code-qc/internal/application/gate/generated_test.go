// These tests cover generated-code markers (TM-3): the marker is file
// content an agent can add, so in a tested layer it exempts nothing from the
// tests gate or the limits; outside tested layers it still exempts a file
// from the limits.

const markerNote = "the generated-code marker does not exempt files in a tested layer"

// markerFacts are keyed by content. The marker texts stand for what each
// language's analyzer recognises; the facts are what it would report.
func markerFacts() map[string]domain.FileFacts {
	short := []domain.FunctionFacts{{Key: "f", Line: 3, Lines: 10}}
	long := []domain.FunctionFacts{{Key: "f", Line: 3, Lines: 80}}
	return map[string]domain.FileFacts{
		"plain":                                  {Functions: short},
		"plain, long":                            {Functions: long},
		"// Code generated by x. DO NOT EDIT.":   {Generated: true, Functions: long},
		"// Code generated by x. DO NOT EDIT. 2": {Generated: true, Functions: short},
		"/** @generated */":                      {Generated: true, Functions: long},
		"/** @generated */ 2":                    {Generated: true, Functions: short},
		"# DO NOT EDIT":                          {Generated: true, Functions: long},
		"# DO NOT EDIT 2":                        {Generated: true, Functions: short},
	}
}

// runMarkerGates runs the tests gate in the full tier and the structure
// gate over one modified file, whose base is base and working content now.
func runMarkerGates(t *testing.T, path, base, now string) []domain.Finding {
	t.Helper()
	analyzer := fakeAnalyzer{facts: markerFacts()}
	analyzers := map[domain.Language]port.Analyzer{domain.LanguageGo: analyzer, domain.LanguagePython: analyzer, domain.LanguageTypeScript: analyzer}
	source := &fakeSource{
		working: map[string]string{path: long(now)},
		base:    map[string]string{path: base},
		changed: map[string]domain.LineSet{path: {Ranges: []domain.LineRange{{First: 1, Last: 5}}}},
	}
	coverage := domain.Coverage{path: {4: 0}}
	runner := &fakeRunner{results: map[string]port.TestResult{
		"go svc": {Coverage: coverage}, "python tts": {Coverage: coverage}, "command api npm test": {Coverage: coverage},
	}}
	in := port.GateInput{Config: testsConfig(t), Changes: domain.ChangeSet{Base: "tree", Files: []domain.ChangedFile{modified(path)}}, Tier: domain.TierFull}
	var all []domain.Finding
	for _, g := range []port.Gate{NewTests(analyzers, source, runner, fakeFinder{"svc": "go.mod"}), NewStructure(analyzers, source)} {
		findings, err := g.Run(t.Context(), in)
		if err != nil {
			t.Fatalf("%s: %v", g.Name(), err)
		}
		all = append(all, findings...)
	}
	return all
}

// markerRules lists the rules of findings, and checks that each is on path
// and carries the marker note (pointing to exclude) exactly when noted.
func markerRules(t *testing.T, findings []domain.Finding, path string, noted bool) []string {
	t.Helper()
	var rules []string
	for _, f := range findings {
		rules = append(rules, f.Rule)
		said := strings.Contains(f.Message, markerNote) && strings.Contains(f.Message, `"exclude" in the config`)
		if f.File != path || said != noted {
			t.Errorf("finding %+v: want it on %s, with the marker note: %v", f, path, noted)
		}
	}
	return rules
}

// TestGeneratedMarkerDoesNotExemptTestedLayers: a marked file in a tested
// layer gets tests-missing, uncovered-change and the limits, whether the
// marker was added in the change or there before, and each finding says why
// the marker did not exempt it (AC-11, AC-14, SR-17).
func TestGeneratedMarkerDoesNotExemptTestedLayers(t *testing.T) {
	tests := []struct {
		name, path, base, now string
	}{
		{"go, marker added", "svc/internal/domain/gen.go", "plain", "// Code generated by x. DO NOT EDIT."},
		{"go, marker there before", "svc/internal/domain/gen.go", "// Code generated by x. DO NOT EDIT. 2", "// Code generated by x. DO NOT EDIT."},
		{"typescript, marker added", "api/src/domain/gen.ts", "plain", "/** @generated */"},
		{"typescript, marker there before", "api/src/domain/gen.ts", "/** @generated */ 2", "/** @generated */"},
		{"python, marker added", "tts/pkg/domain.py", "plain", "# DO NOT EDIT"},
		{"python, marker there before", "tts/pkg/domain.py", "# DO NOT EDIT 2", "# DO NOT EDIT"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := markerRules(t, runMarkerGates(t, tt.path, tt.base, tt.now), tt.path, true)
			if want := "tests-missing uncovered-change function-length"; strings.Join(got, " ") != want {
				t.Fatalf("rules = %q, want %q", got, want)
			}
		})
	}
}

// TestGeneratedMarkerOutsideTestedLayers: outside tested layers the marker
// still exempts a file from the limits (AC-13), and a finding on an
// unmarked file carries no note.
func TestGeneratedMarkerOutsideTestedLayers(t *testing.T) {
	tests := []struct {
		name, path, now string
		want            string
	}{
		{"marked, untested layer", "svc/internal/infrastructure/gen.go", "// Code generated by x. DO NOT EDIT.", ""},
		{"marked, in no layer", "svc/tools/gen.go", "// Code generated by x. DO NOT EDIT.", ""},
		{"unmarked, untested layer", "svc/internal/infrastructure/gen.go", "plain, long", "function-length"},
		{"unmarked, tested layer", "svc/internal/domain/gen.go", "plain, long", "tests-missing uncovered-change function-length"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := markerRules(t, runMarkerGates(t, tt.path, "plain", tt.now), tt.path, false)
			if strings.Join(got, " ") != tt.want {
				t.Fatalf("rules = %q, want %q", got, tt.want)
			}
		})
	}
}
